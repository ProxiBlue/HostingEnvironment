#!/usr/bin/env bash
# provision-cp.sh - Idempotent provisioning of the PHP box (AppServer / cp).
#
# Run by addons/phpbox-addon.jps on install, after every container redeploy
# (GUI "Redeploy Containers" -> new PHP tag) and from the "Re-apply" button.
# Safe to re-run at any time; every step checks before it writes.
#
# Inputs (env vars). Values are persisted to /etc/phpbox.env (kept across
# redeploys via redeploy.conf) so later runs can omit them.
#   SITE_PROFILE     magento | drupal. Picks nginx vhost, fail2ban jails,
#                    crons and the health probe. Default: magento.
#   DOCROOT          nginx document root. Default by profile:
#                    magento /var/www/webroot/ROOT/pub, drupal /var/www/webroot/ROOT/web
#   DB_HOST          internal IP of the services-env DB node          (required once)
#   REDIS_HOST       internal IP of the services-env Redis node       (optional)
#   ES_HOST          internal IP of the services-env OpenSearch node  (optional)
#   BACKUP_EMAIL     alerts + backup failure mail                     (required once)
#   MONITOR_SSH_KEY  optional. ssh public key of the services-node monitor
#                    (n8n). Appended to nginx's authorized_keys.
#   REPO_REF         git ref of ProxiBlue/HostingEnvironment to pull
#                    configs from. Default: main.
set -euo pipefail

ENV_FILE=/etc/phpbox.env
CREDS_FILE=/root/phpbox-credentials.txt
LOG=/var/log/phpbox-provision.log
REDEPLOY_CONF=/etc/jelastic/redeploy.conf
SNAPSHOT_BIN=/usr/local/bin/n8n-server-snapshot.sh
VHOST=/etc/nginx/conf.d/SITES_ENABLED/site-default.conf

log() { echo "[provision-cp] $*" | tee -a "$LOG"; }
die() { echo "[provision-cp] FATAL: $*" | tee -a "$LOG" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "must run as root"
touch "$LOG"

# --- inputs ----------------------------------------------------------------

load_env() {
  # Explicit (non-empty) env wins; anything unset falls back to the persisted file.
  if [ -f "$ENV_FILE" ]; then
    while IFS='=' read -r k v; do
      [ -z "$k" ] && continue
      case "$k" in \#*) continue ;; esac
      v="${v%\"}"; v="${v#\"}"
      if [ -z "${!k:-}" ]; then export "$k=$v"; fi
    done < "$ENV_FILE"
  fi
  : "${REPO_REF:=main}"
  : "${SITE_PROFILE:=magento}"
  : "${MONITOR_SSH_KEY:=}"
  : "${REDIS_HOST:=}"
  : "${ES_HOST:=}"
  case "$SITE_PROFILE" in
    magento) : "${DOCROOT:=/var/www/webroot/ROOT/pub}" ;;
    drupal)  : "${DOCROOT:=/var/www/webroot/ROOT/web}" ;;
    *) die "SITE_PROFILE must be magento or drupal (got '$SITE_PROFILE')" ;;
  esac
  for v in DB_HOST BACKUP_EMAIL; do
    [ -n "${!v:-}" ] || die "$v not set and not in $ENV_FILE"
  done
  REPO_BASE="https://raw.githubusercontent.com/ProxiBlue/HostingEnvironment/${REPO_REF}"
}

persist_env() {
  umask 077
  cat > "$ENV_FILE" <<EOF
# Written by provision-cp.sh. Edit, then re-run the add-on's "Re-apply".
SITE_PROFILE="$SITE_PROFILE"
DOCROOT="$DOCROOT"
DB_HOST="$DB_HOST"
REDIS_HOST="$REDIS_HOST"
ES_HOST="$ES_HOST"
BACKUP_EMAIL="$BACKUP_EMAIL"
REPO_REF="$REPO_REF"
EOF
  umask 022
}

fetch() {
  # fetch <repo-relative path> <dest>
  curl -fsSL "$REPO_BASE/$1" -o "$2.tmp" || die "download failed: $1"
  mv "$2.tmp" "$2"
}

# --- secrets ---------------------------------------------------------------

gen_pw() { openssl rand -base64 24 | tr -dc 'A-Za-z0-9' | head -c 16; }

ensure_secrets() {
  if [ ! -f "$CREDS_FILE" ]; then
    log "generating credentials -> $CREDS_FILE"
    umask 077
    cat > "$CREDS_FILE" <<EOF
# PHP box credentials (generated by provision-cp.sh, kept across redeploys)
SYSTEM_PASS=$(gen_pw)
STATS_PASS=$(gen_pw)
MONIT_PASS=$(gen_pw)
EOF
    umask 022
  fi
  # shellcheck disable=SC1090
  . "$CREDS_FILE"
}

apply_system_passwords() {
  # /etc/shadow is reset by a redeploy; re-apply so SSH/web-SSH logins and
  # "su root" from nginx keep working. chpasswd ships with shadow-utils
  # (always present); passwd itself is not in every image.
  printf 'root:%s\nnginx:%s\n' "$SYSTEM_PASS" "$SYSTEM_PASS" | chpasswd >>"$LOG" 2>&1 \
    || die "chpasswd failed"
}

# --- packages --------------------------------------------------------------

install_packages() {
  if ! rpm -q epel-release >/dev/null 2>&1; then
    yum install -y epel-release >>"$LOG" 2>&1
  fi
  local major=0
  if command -v node >/dev/null 2>&1; then
    major="$(node -p 'process.versions.node.split(".")[0]' 2>/dev/null || echo 0)"
  fi
  if [ "${major:-0}" -lt 22 ]; then
    log "installing Node.js 22.x (NodeSource)"
    curl -fsSL https://rpm.nodesource.com/setup_22.x | bash - >>"$LOG" 2>&1
    yum install -y nodejs >>"$LOG" 2>&1
  fi
  # iptables-nft: fail2ban's iptables-multiport action needs the iptables
  # binary; the plain docker image has only nft.
  local want="joe pv monit libsodium httpd-tools goaccess libwebp-tools fail2ban unzip s-nail redis passwd iptables-nft"
  local missing=""
  for p in $want; do rpm -q "$p" >/dev/null 2>&1 || missing="$missing $p"; done
  if [ -n "$missing" ]; then
    log "installing:$missing"
    # shellcheck disable=SC2086
    yum install -y $missing >>"$LOG" 2>&1
  fi
}

install_awscli() {
  command -v aws >/dev/null 2>&1 && return 0
  log "installing AWS CLI v2"
  local tmp; tmp="$(mktemp -d)"
  curl -fsSL "https://awscli.amazonaws.com/awscli-exe-linux-x86_64.zip" -o "$tmp/awscliv2.zip"
  unzip -q "$tmp/awscliv2.zip" -d "$tmp"
  "$tmp/aws/install" --update >>"$LOG" 2>&1
  rm -rf "$tmp"
}

# --- PHP -------------------------------------------------------------------

php_config() {
  # /etc/php.d survives a redeploy, which is exactly why it must be
  # regenerated: a stale extensions.ini from the previous PHP line breaks the
  # new one (imap.so gone in 8.4, opcache built in from 8.5).
  fetch configs/php/custom.ini      /etc/php.d/custom.ini
  fetch configs/php/extensions.ini  /etc/php.d/extensions.ini
  fetch configs/php/assert_off.ini  /etc/php.d/assert_off.ini
  fetch configs/php/error-level.ini /etc/php.d/error-level.ini
  fetch configs/php/php-fpm.conf    /etc/php-fpm.conf
  if php -n -r 'exit(extension_loaded("Zend OPcache") ? 0 : 1);'; then
    sed -i '/^zend_extension=.*opcache\.so/d' /etc/php.d/extensions.ini
  fi
  # Drop extension lines whose .so does not exist in this image.
  local extdir; extdir="$(php -n -r 'echo ini_get("extension_dir");')"
  while IFS= read -r line; do
    local so; so="$(echo "$line" | sed -E 's/^(zend_)?extension=//; s/[[:space:]]+$//')"
    [ -f "$extdir/$so" ] || [ -f "$so" ] || {
      log "extensions.ini: $so not in $extdir, dropping line"
      sed -i "\|^${line}$|d" /etc/php.d/extensions.ini
    }
  done < <(grep -E '^(zend_)?extension=' /etc/php.d/extensions.ini || true)
}

# --- NGINX -----------------------------------------------------------------

nginx_config() {
  fetch configs/nginx/nginx.conf        /etc/nginx/nginx.conf
  fetch configs/nginx/nossl.conf        /etc/nginx/conf.d/nossl.conf
  sed -i "s|__DOCROOT__|$DOCROOT|g" /etc/nginx/conf.d/nossl.conf
  fetch configs/nginx/stub_status.conf  /etc/nginx/conf.d/stub_status.conf
  # Let's Encrypt add-on owns ssl.conf once installed; never overwrite it.
  if [ ! -f /etc/nginx/conf.d/ssl.conf ]; then
    fetch configs/nginx/ssl.conf.disabled /etc/nginx/conf.d/ssl.conf.disabled
  fi
  mkdir -p /etc/nginx/conf.d/SITES_ENABLED /etc/nginx/conf.d/CORS
  # Per-site vhost is customised in place after install - seed only once.
  if [ ! -f "$VHOST" ]; then
    case "$SITE_PROFILE" in
      magento) fetch configs/nginx/site-default-mg2.conf    "$VHOST" ;;
      drupal)  fetch configs/nginx/site-default-drupal.conf "$VHOST" ;;
    esac
    sed -i "s|__DOCROOT__|$DOCROOT|g" "$VHOST"
    log "seeded $SITE_PROFILE vhost, docroot $DOCROOT"
  fi
  if [ ! -f /etc/nginx/conf.d/CORS/cors.conf ]; then
    fetch configs/nginx/CORS-CDN/cors.conf /etc/nginx/conf.d/CORS/cors.conf
  fi
  if [ ! -f /etc/nginx/.htpasswd ]; then
    htpasswd -b -c /etc/nginx/.htpasswd stats "$STATS_PASS" >>"$LOG" 2>&1
    chown nginx:nginx /etc/nginx/.htpasswd
  fi
  mkdir -p /var/www/webroot/site_report
  chown nginx:nginx /var/www/webroot/site_report
  nginx -t >>"$LOG" 2>&1 || die "nginx -t failed, see $LOG"
}

# --- local Redis (page/object cache, unix socket) --------------------------

redis_local() {
  # The plain docker node type does not honour REDIS_ENABLED (that is the
  # nginxphp-dockerized stack's jem hook), so the server comes from AppStream
  # (install_packages). EL9 unit reads /etc/redis/redis.conf.
  local conf; conf="$(grep -oE '/etc/redis[^ ]*\.conf' /usr/lib/systemd/system/redis.service | head -1)"
  : "${conf:=/etc/redis/redis.conf}"
  mkdir -p "$(dirname "$conf")" /var/lib/redis /var/log/redis
  fetch configs/redis/redis-local.conf "$conf"
  chown redis:redis "$conf" /var/lib/redis /var/log/redis
  mkdir -p /etc/systemd/system/redis.service.d
  fetch configs/restart.conf /etc/systemd/system/redis.service.d/restart.conf
  systemctl daemon-reload
  systemctl enable redis >>"$LOG" 2>&1 || true
  systemctl restart redis >>"$LOG" 2>&1 || die "redis failed to start, see $LOG and /var/log/redis/redis.log"
}

# --- hosts / environment ---------------------------------------------------

set_host() { # set_host NAME IP
  sed -i "/[[:space:]]$1\$/d" /etc/hosts
  echo "$2 $1" >> /etc/hosts
}

hosts_and_env() {
  set_host DB_MASTER "$DB_HOST"
  [ -n "$REDIS_HOST" ] && set_host RD_MASTER "$REDIS_HOST"
  [ -n "$ES_HOST" ]    && set_host ES_MASTER "$ES_HOST"
  sed -i '/^export BACKUP_FAIL_/d' /etc/environment
  {
    echo "export BACKUP_FAIL_FROM=$BACKUP_EMAIL"
    echo "export BACKUP_FAIL_TO=$BACKUP_EMAIL"
  } >> /etc/environment
  return 0
}

# --- fail2ban --------------------------------------------------------------

fail2ban_jails() {
  case "$SITE_PROFILE" in
    drupal) echo "nginx-badurls nginx-drupal-login" ;;
    *)      echo "nginx-badurls nginx-search nginx-magento-admin" ;;
  esac
}

fail2ban_config() {
  cp /etc/fail2ban/jail.conf /etc/fail2ban/jail.local
  sed -i 's/findtime  = 10m/findtime = 50/g' /etc/fail2ban/jail.local
  sed -i 's/maxretry = 5/maxretry = 3/g' /etc/fail2ban/jail.local
  sed -i "s/sender = root@<fq-hostname>/sender = $BACKUP_EMAIL/g" /etc/fail2ban/jail.local
  sed -i "s/destemail = root@localhost/destemail = $BACKUP_EMAIL/g" /etc/fail2ban/jail.local
  sed -i 's/action = %(action_)s/action = %(action_mwl)s/g' /etc/fail2ban/jail.local
  for f in $(fail2ban_jails); do
    fetch "configs/fail2ban/filter.d/$f.conf" "/etc/fail2ban/filter.d/$f.conf"
    fetch "configs/fail2ban/jail.d/$f.conf"   "/etc/fail2ban/jail.d/$f.conf"
  done
  fetch configs/fail2ban/fail2banUpdate.sh /root/fail2banUpdate.sh
  chmod +x /root/fail2banUpdate.sh
  systemctl enable fail2ban >>"$LOG" 2>&1
  systemctl restart fail2ban >>"$LOG" 2>&1
}

# --- monit -----------------------------------------------------------------

monit_config() {
  mkdir -p /etc/monit.d
  fetch configs/monit/nginxmonitor  /etc/monit.d/nginx
  fetch configs/monit/phpfpmmonitor /etc/monit.d/phpfpm
  fetch configs/monit/redismonitor  /etc/monit.d/redis
  sed -i -e '/use address localhost/d' -e '/allow localhost/d' /etc/monitrc
  sed -i -E "s/allow admin:.*/allow admin:$MONIT_PASS/" /etc/monitrc
  grep -q "allow admin:$MONIT_PASS" /etc/monitrc || echo "    allow admin:$MONIT_PASS" >> /etc/monitrc
  systemctl enable monit >>"$LOG" 2>&1
  systemctl restart monit >>"$LOG" 2>&1
}

# --- logrotate / cron ------------------------------------------------------

logrotate_config() {
  fetch configs/logrotate/magento-stack /etc/logrotate.d/php-stack
  rm -f /etc/logrotate.d/magento-stack
}

cron_line() { # cron_line USER 'line'  (append if absent)
  local user="$1" line="$2" file="/var/spool/cron/$1"
  touch "$file"
  grep -qF -- "$line" "$file" || echo "$line" >> "$file"
  chown "$user:$user" "$file"
  chmod 0600 "$file"
}

crons() {
  cron_line root  "0 5 * * * /bin/bash /root/fail2banUpdate.sh >/var/log/fail2ban-update.log 2>&1"
  # /var/spool/cron/nginx survives redeploys; these only seed a fresh box.
  cron_line nginx "0 1 * * * zcat /var/log/nginx/access*.gz | grep -v -f /var/www/webroot/ROOT/go_access_exclude_list.txt | goaccess -o /var/www/webroot/site_report/index.html --log-format=COMBINED - 2>&1 >/dev/null"
  if [ "$SITE_PROFILE" = magento ]; then
    cron_line nginx "0 5 * * * /bin/bash /var/www/webroot/ROOT/backup/backup_to_s3.sh media 2>&1 >/var/www/webroot/ROOT/var/log/backups.log"
    cron_line nginx "5 8 * * 0 rm -rf /var/www/webroot/ROOT/pub/media/import/* 2>&1 >/dev/null"
  fi
}

# --- remote monitoring hooks (services node -> this box) -------------------

monitor_access() {
  # Snapshot collector runs here as root; the services node's n8n calls it
  # over SSH as nginx: ssh nginx@<this box> sudo /usr/local/bin/n8n-server-snapshot.sh
  fetch configs/n8n/n8n-server-snapshot.sh "$SNAPSHOT_BIN"
  chown root:root "$SNAPSHOT_BIN"; chmod 0755 "$SNAPSHOT_BIN"
  cat > /etc/sudoers.d/phpbox-monitor <<EOF
# services-node monitor (n8n over ssh as nginx) - read-only snapshot only
nginx ALL=(root) NOPASSWD: $SNAPSHOT_BIN
EOF
  chmod 0440 /etc/sudoers.d/phpbox-monitor
  visudo -cf /etc/sudoers.d/phpbox-monitor >/dev/null || die "sudoers fragment invalid"

  if [ -n "$MONITOR_SSH_KEY" ]; then
    local ak=/var/lib/nginx/.ssh/authorized_keys
    install -d -m 0700 -o nginx -g nginx /var/lib/nginx/.ssh
    touch "$ak"; chown nginx:nginx "$ak"; chmod 0600 "$ak"
    grep -qF -- "$MONITOR_SSH_KEY" "$ak" || { echo "$MONITOR_SSH_KEY" >> "$ak"; log "monitor ssh key authorised for nginx"; }
  fi
}

# --- redeploy.conf: keep what the hook cannot regenerate --------------------

redeploy_conf() {
  [ -f "$REDEPLOY_CONF" ] || { log "no $REDEPLOY_CONF, skipping"; return 0; }
  local keep=(
    "$ENV_FILE"
    "$CREDS_FILE"
    /root/.ssh/
    /etc/nginx/.htpasswd
    /etc/nginx/conf.d/SITES_ENABLED/
    /etc/nginx/conf.d/CORS/
    /var/spool/cron/root
    /var/lib/redis/
  )
  for p in "${keep[@]}"; do
    grep -qxF -- "$p" "$REDEPLOY_CONF" && continue
    # Insert under the CUSTOM header so the SYSTEM block stays untouched.
    sed -i "/^# CUSTOM FILES AND FOLDERS/a $p" "$REDEPLOY_CONF"
    log "redeploy.conf: keep $p"
  done
}

# --- services --------------------------------------------------------------

restart_services() {
  systemctl restart nginx >>"$LOG" 2>&1
  jem service restart >>"$LOG" 2>&1 || systemctl restart php-fpm >>"$LOG" 2>&1
}

verify() {
  local ok=1
  for s in nginx php-fpm redis monit fail2ban; do
    systemctl is-active --quiet "$s" || { log "VERIFY: $s not active"; ok=0; }
  done
  local probe=/
  [ "$SITE_PROFILE" = magento ] && probe=/health_check.php
  local code; code="$(curl -s -o /dev/null -w '%{http_code}' --max-time 10 "http://127.0.0.1$probe" || true)"
  log "VERIFY: $probe -> HTTP $code (no code deployed yet = 404/403, fine)"
  log "VERIFY: DB_MASTER tcp 3306 -> $(timeout 5 bash -c "</dev/tcp/$DB_HOST/3306" 2>/dev/null && echo open || echo CLOSED)"
  [ "$ok" -eq 1 ] || die "verification failed"
  log "PHP $(php -r 'echo PHP_VERSION;') / $(nginx -v 2>&1) / profile $SITE_PROFILE provisioned OK"
}

main() {
  load_env
  log "start (profile=$SITE_PROFILE, docroot=$DOCROOT, REPO_REF=$REPO_REF, DB=$DB_HOST, REDIS=${REDIS_HOST:--}, ES=${ES_HOST:--})"
  persist_env
  ensure_secrets
  apply_system_passwords
  install_packages
  install_awscli
  php_config
  nginx_config
  redis_local
  hosts_and_env
  fail2ban_config
  monit_config
  logrotate_config
  crons
  monitor_access
  redeploy_conf
  restart_services
  verify
}

main "$@"
